"""Writes 数艺工坊's themes from its one token file, and checks that the code stays on the design.

design/ui/tokens.json is the only place a colour, font size, radius, spacing or duration of the
interface is decided. This script writes three files from it:

- desktop/.../theme/light.css and dark.css: the JavaFX looked-up colours (`-dc-*`) and Modena's
  own variables, for `.root` and `.root:dark`;
- design/ui/tokens.css: the same colours as CSS custom properties (`--dc-*`) for the design
  prototype design/ui/index.html, light by default, dark under `[data-theme="dark"]` and, unless
  light is chosen, under `prefers-color-scheme: dark`.

With --check it writes nothing and fails when a generated file is stale, when base.css uses a
`-dc-*` colour the tokens do not define, when a token is used nowhere, or when base.css uses a font
size, corner radius or padding that is not on the scales. Standard library only.

Usage: python3 -B design/ui/build.py [--check] [--root REPOSITORY_ROOT]
Exit status: 0 when written or current, 1 when --check finds a difference.
"""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
TOKENS = "design/ui/tokens.json"
WEB_TOKENS = "design/ui/tokens.css"
THEME_DIR = "desktop/src/main/resources/com/example/datacraft/desktop/theme"
BASE_CSS = THEME_DIR + "/base.css"
JAVA_SOURCES = "desktop/src/main/java"
THEMES = (("light", ".root"), ("dark", ".root:dark"))

COLOUR = re.compile(
    r"#[0-9A-F]{6}|rgba\(\d{1,3}, \d{1,3}, \d{1,3}, (?:0|1|0\.\d{1,2})\)")
NAME = re.compile(r"[a-z]+(?:-[a-z]+)*")
TOKEN_USE = re.compile(r"-dc-([a-z]+(?:-[a-z]+)*)")
FONT_SIZE = re.compile(r"-fx-font-size:\s*([\d.]+)px")
RADIUS = re.compile(r"-fx-(?:background|border)-radius:\s*([^;]+);")
PADDING = re.compile(r"-fx-(?:padding|spacing|hgap|vgap):\s*([^;]+);")

HEADER = ("/* Generated by design/ui/build.py from design/ui/tokens.json: edit the tokens, "
          "not this file. */\n")


class DesignError(Exception):
    """The token file is malformed."""


def load(root):
    try:
        tokens = json.loads((Path(root) / TOKENS).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise DesignError(f"cannot read {TOKENS}: {error}") from error
    names = set()
    for group in tokens["colors"]:
        for name, values in group["tokens"].items():
            if not NAME.fullmatch(name) or name in names:
                raise DesignError(f"token name '{name}' is malformed or defined twice")
            names.add(name)
            check_pair(name, values)
    for name, values in tokens["modena"]["tokens"].items():
        if not name.startswith("-fx-"):
            raise DesignError(f"Modena variable '{name}' must start with -fx-")
        for value in values:
            if value.startswith("@") and value[1:] not in names:
                raise DesignError(f"{name} names the undefined token {value}")
        check_pair(name, [value for value in values if not value.startswith("@")], partial=True)
    return tokens


def check_pair(name, values, partial=False):
    if not partial and len(values) != 2:
        raise DesignError(f"'{name}' needs a light and a dark value")
    for value in values:
        if not COLOUR.fullmatch(value):
            raise DesignError(f"'{name}': '{value}' is not #RRGGBB or rgba(r, g, b, a)")


def colours(tokens, index):
    """(group comment, [(name, value)]) for one theme; index 0 is light, 1 dark."""
    return [(group["group"], [(name, values[index]) for name, values in group["tokens"].items()])
            for group in tokens["colors"]]


def modena(tokens, index):
    table = {name: values[index] for group in tokens["colors"]
             for name, values in group["tokens"].items()}
    return [(name, table[values[index][1:]] if values[index].startswith("@") else values[index])
            for name, values in tokens["modena"]["tokens"].items()]


def javafx_theme(tokens, theme):
    index = 0 if theme == "light" else 1
    selector = dict(THEMES)[theme]
    lines = [HEADER]
    if theme == "light":
        lines.append("/* 数艺工坊 light theme: colour tokens only. Layout and shapes live in base.css. */\n")
    else:
        lines.append(
            "/*\n"
            " * 数艺工坊 dark theme: a blue-tinted night, not near-black with one neon accent. Both theme\n"
            " * files are always loaded; these tokens depend on the root's \"dark\" pseudo-class, so a\n"
            " * theme switch updates CSS state without rematching the whole tree's base selectors.\n"
            " */\n")
    lines.append(selector + " {\n")
    for group, entries in colours(tokens, index):
        lines.append(f"    /* {group} */\n")
        lines.extend(f"    -dc-{name}: {value};\n" for name, value in entries)
        lines.append("\n")
    lines.append("    /* Modena's own variables, so stock controls and popups follow the theme. */\n")
    lines.extend(f"    {name}: {value};\n" for name, value in modena(tokens, index))
    lines.append("}\n")
    return "".join(lines)


def web_tokens(tokens):
    def block(selector, index, indent=""):
        out = [f"{indent}{selector} {{\n"]
        for group, entries in colours(tokens, index):
            out.append(f"{indent}    /* {group} */\n")
            out.extend(f"{indent}    --dc-{name}: {value};\n" for name, value in entries)
        if index == 0:
            for scale in ("type", "radius", "motion"):
                for name, value in tokens[scale]["scale"].items():
                    unit = "ms" if scale == "motion" else "px"
                    out.append(f"{indent}    --dc-{scale}-{name}: {value}{unit};\n")
        out.append(f"{indent}}}\n")
        return "".join(out)

    return (HEADER
            + "/* The prototype's colours: light by default, dark when chosen or when the system is dark. */\n"
            + block(":root", 0) + "\n"
            + block(':root[data-theme="dark"]', 1) + "\n"
            + "@media (prefers-color-scheme: dark) {\n"
            + block(':root:not([data-theme="light"])', 1, "    ")
            + "}\n")


def outputs(root, tokens):
    root = Path(root)
    return {
        root / THEME_DIR / "light.css": javafx_theme(tokens, "light"),
        root / THEME_DIR / "dark.css": javafx_theme(tokens, "dark"),
        root / WEB_TOKENS: web_tokens(tokens),
    }


def numbers(value):
    return [float(part.rstrip("px")) for part in value.replace(",", " ").split()]


def contract_problems(root, tokens):
    """What base.css and the Java sources do that the tokens do not allow."""
    root = Path(root)
    base = (root / BASE_CSS).read_text(encoding="utf-8")
    defined = {name for group in tokens["colors"] for name in group["tokens"]}
    problems = []
    used_in_css = set(TOKEN_USE.findall(base))
    for name in sorted(used_in_css - defined):
        problems.append(f"{BASE_CSS} uses -dc-{name}, which design/ui/tokens.json does not define")
    java = "\n".join(path.read_text(encoding="utf-8")
                     for path in sorted((root / JAVA_SOURCES).rglob("*.java")))
    used = used_in_css | set(TOKEN_USE.findall(java))
    for name in sorted(defined - used):
        problems.append(f"token '{name}' is used neither in {BASE_CSS} nor in the Java sources")
    sizes = set(tokens["type"]["scale"].values())
    for match in FONT_SIZE.finditer(base):
        if float(match.group(1)) not in sizes:
            problems.append(f"{BASE_CSS}:{line_of(base, match)}: font size {match.group(1)}px "
                            f"is not on the type scale {sorted(sizes)}")
    radii = set(tokens["radius"]["scale"].values())
    for match in RADIUS.finditer(base):
        for value in numbers(match.group(1)):
            if value not in radii:
                problems.append(f"{BASE_CSS}:{line_of(base, match)}: radius {value:g} is not on "
                                f"the radius scale {sorted(radii)}")
    for match in PADDING.finditer(base):
        for value in numbers(match.group(1)):
            # 1 px is the hairline of a divider, the only odd value allowed.
            if value % 2 and value != 1:
                problems.append(f"{BASE_CSS}:{line_of(base, match)}: spacing {value:g} is off "
                                f"the 2 px grid")
    return problems


def line_of(text, match):
    return text.count("\n", 0, match.start()) + 1


def main(argv=None):
    parser = argparse.ArgumentParser(description="Writes or checks the themes generated from the design tokens.")
    parser.add_argument("--check", action="store_true", help="write nothing; fail on any difference")
    parser.add_argument("--root", type=Path, default=ROOT)
    arguments = parser.parse_args(argv)
    try:
        tokens = load(arguments.root)
    except DesignError as problem:
        print(f"design: {problem}", file=sys.stderr)
        return 1
    stale = []
    for path, text in outputs(arguments.root, tokens).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if arguments.check:
            stale.append(path.relative_to(arguments.root).as_posix())
        else:
            path.write_text(text, encoding="utf-8", newline="")
            print(f"wrote {path.relative_to(arguments.root).as_posix()}")
    problems = [f"{name} is stale: run python3 -B design/ui/build.py" for name in stale]
    problems += contract_problems(arguments.root, tokens)
    for problem in problems:
        print(f"design: {problem}", file=sys.stderr)
    if not problems:
        print("design: tokens, themes and base.css agree")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
